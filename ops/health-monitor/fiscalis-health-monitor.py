def _hmac(key: bytes, text: str) -> bytes:
    return hmac.new(key, text.encode("utf-8"), hashlib.sha256).digest()


def canonical_query(query: Mapping[str, str]) -> str:
    quote = lambda s: urllib.parse.quote(s, safe="-_.~")  # noqa: E731
    return "&".join(f"{quote(k)}={quote(v)}" for k, v in sorted(query.items()))


def sigv4_authorization(
    method: str, canonical_uri: str, query: str, headers: Mapping[str, str], payload_hash: str,
    access_key: str, secret_key: str, region: str, service: str, amz_date: str,
) -> str:  # fmt: skip
    """AWS Signature Version 4 ``Authorization`` header; `headers` includes host."""
    signed = {k.lower(): " ".join(str(v).split()) for k, v in headers.items()}
    names = sorted(signed)
    canonical = "\n".join([
        method, canonical_uri, query, "".join(f"{n}:{signed[n]}\n" for n in names),
        ";".join(names), payload_hash,
    ])  # fmt: skip
    scope = f"{amz_date[:8]}/{region}/{service}/aws4_request"
    to_sign = "\n".join(
        ["AWS4-HMAC-SHA256", amz_date, scope, hashlib.sha256(canonical.encode("utf-8")).hexdigest()]
    )
    key = _hmac(("AWS4" + secret_key).encode("utf-8"), amz_date[:8])
    for part in (region, service, "aws4_request"):
        key = _hmac(key, part)
    signature = hmac.new(key, to_sign.encode("utf-8"), hashlib.sha256).hexdigest()
    return (f"AWS4-HMAC-SHA256 Credential={access_key}/{scope}, "
            f"SignedHeaders={';'.join(names)}, Signature={signature}")  # fmt: skip


class S3:
    """Path-style, read-only S3 calls (HEAD object, ListObjectsV2), signed here."""

    def __init__(self, bucket: str, access_key: str, secret_key: str, opener: Opener,
                 clock: Callable[[], float] = time.time, sleep: Callable[[float], None] = time.sleep):  # fmt: skip
        self.bucket, self.access_key, self.secret_key = bucket, access_key, secret_key
        self.opener, self.clock, self.sleep = opener, clock, sleep

    def request(self, method: str, key: str = "", query: Mapping[str, str] | None = None,
                extra: Mapping[str, str] | None = None) -> tuple[int, Mapping[str, str], bytes]:  # fmt: skip
        uri = urllib.parse.quote(f"/{self.bucket}" + (f"/{key}" if key else ""), safe="/-_.~")
        qs = canonical_query(query or {})
        for attempt in range(3):
            amz_date = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime(self.clock()))
            headers = {"host": S3_HOST, "x-amz-content-sha256": EMPTY_SHA256, "x-amz-date": amz_date,
                       **(extra or {})}  # fmt: skip
            auth = sigv4_authorization(method, uri, qs, headers, EMPTY_SHA256, self.access_key,
                                       self.secret_key, S3_REGION, "s3", amz_date)  # fmt: skip
            sent = {k: v for k, v in headers.items() if k != "host"}
            request = urllib.request.Request(
                f"https://{S3_HOST}{uri}" + (f"?{qs}" if qs else ""),
                headers={**sent, "Authorization": auth, "User-Agent": "fiscalis-health-monitor"},
                method=method,
            )
            try:
                with self.opener(request, timeout=HTTP_TIMEOUT) as response:
                    return response.status, response.headers, response.read()
            except urllib.error.HTTPError as error:
                if error.code < 500 or attempt == 2:
                    return error.code, error.headers, b""
            except (urllib.error.URLError, http.client.HTTPException, OSError) as error:
                if attempt == 2:
                    raise NotifyError(f"S3 {method} {type(error).__name__}") from None
            self.sleep(2 * (attempt + 1))
        raise AssertionError("unreachable")

    def head(self, key: str) -> tuple[int, Mapping[str, str]]:
        status, headers, _ = self.request("HEAD", key, extra={"x-amz-checksum-mode": "ENABLED"})
        return status, headers

    def list(self, prefix: str) -> list[tuple[str, int]]:
        objects, token = [], None
        for _ in range(1000):
            query = {"list-type": "2", "prefix": prefix, **({"continuation-token": token} if token else {})}
            status, _, raw = self.request("GET", query=query)
            if status != 200:
                raise NotifyError(f"S3 list HTTP {status}")
            root = ET.fromstring(raw)
            for item in root.iter(f"{S3_NS}Contents"):
                objects.append((item.findtext(f"{S3_NS}Key") or "", int(item.findtext(f"{S3_NS}Size") or 0)))
            token = root.findtext(f"{S3_NS}NextContinuationToken")
            if root.findtext(f"{S3_NS}IsTruncated") != "true" or not token:
                return objects
        raise NotifyError("S3 list did not end")


def day_key(prefix: str, day: str) -> str:
    return f"{prefix}/minute/{day[:4]}/{day[5:7]}/{day}.jsonl.gz"


def day_ranges(days: list[datetime.date]) -> list[str]:
    """Consecutive days folded into ``first..last`` ranges."""
    out: list[list[datetime.date]] = []
    for day in sorted(days):
        if out and (day - out[-1][1]).days == 1:
            out[-1][1] = day
        else:
            out.append([day, day])
    return [f"{a}" if a == b else f"{a}..{b}" for a, b in out]


def audit_archive(ledger: Any, s3: Any, bucket: str, yesterday: datetime.date) -> tuple[list[str], dict]:
    """Problems found comparing the ledger and the bucket, and counts."""
    if not isinstance(ledger, dict) or not isinstance(ledger.get("days"), list):
        return ["ledger: not a ledger"], {}
    if ledger.get("archiveEnabled") is not True:
        return ["ledger: archive disabled on the deployment"], {}
    prefix = ledger.get("prefix")
    if not isinstance(prefix, str) or not _PREFIX.fullmatch(prefix):
        return ["ledger: no valid prefix"], {}
    if ledger.get("bucket") not in (None, bucket):
        return [f"ledger bucket {flatten(str(ledger.get('bucket')), 64)} is not {bucket}"], {}
    problems = []
    for entry in ledger["days"]:
        day = entry.get("day") if isinstance(entry, dict) else None
        if not isinstance(day, str) or not _DAY.fullmatch(day):
            problems.append("ledger: an entry has no valid day")
            continue
        key, sha, size = entry.get("key"), entry.get("sha256"), entry.get("bytes")
        if key != day_key(prefix, day) or not isinstance(sha, str) or not _SHA256.fullmatch(sha.lower()) \
                or not isinstance(size, int) or isinstance(size, bool):
            problems.append(f"{day}: ledger entry malformed")
            continue
        status, headers = s3.head(key)
        if status == 404:
            problems.append(f"{day}: in the ledger but not in S3")
            continue
        if status != 200:
            problems.append(f"{day}: S3 HEAD HTTP {status}")
            continue
        stored = headers.get("x-amz-checksum-sha256")
        try:
            stored_hex = base64.b64decode(stored or "", validate=True).hex() if stored else None
        except (binascii.Error, ValueError):
            stored_hex = "invalid"
        if stored_hex is None:
            problems.append(f"{day}: S3 object has no SHA-256 checksum")
        elif stored_hex != sha.lower():
            problems.append(f"{day}: SHA-256 differs from the ledger")
        if str(headers.get("Content-Length")) != str(size):
            problems.append(f"{day}: size {flatten(str(headers.get('Content-Length')), 20)} B, ledger {size} B")
    objects = s3.list(f"{prefix}/minute/")
    present = set()
    pattern = re.compile(re.escape(prefix) + r"/minute/(\d{4})/(\d{2})/((\d{4})-(\d{2})-\d{2})\.jsonl\.gz")
    for key, size in objects:
        match = pattern.fullmatch(key)
        if not match or match.group(1) != match.group(4) or match.group(2) != match.group(5):
            continue
        try:
            day = datetime.date.fromisoformat(match.group(3))
        except ValueError:
            continue
        if size <= 0:
            problems.append(f"{day}: S3 object is empty")
        present.add(day)
    expected = (yesterday - ARCHIVE_FIRST_DAY).days + 1
    missing = [ARCHIVE_FIRST_DAY + datetime.timedelta(days=i) for i in range(expected)]
    missing = [d for d in missing if d not in present]
    if missing:
        ranges = day_ranges(missing)
        problems.append(f"{len(missing)} day(s) missing in S3: " + ", ".join(ranges[:5])
                        + (f" and {len(ranges) - 5} more ranges" if len(ranges) > 5 else ""))  # fmt: skip
    return problems, {"ledger_days": len(ledger["days"]), "objects": len(objects), "expected_days": expected}


def fetch_json(url: str, opener: Opener, sleep: Callable[[float], None] = time.sleep,
               headers: Mapping[str, str] | None = None, what: str = "ledger") -> Any:  # fmt: skip
    """GET JSON, 3 tries on 5xx and transport errors; errors name `what`, never a header."""
    request = urllib.request.Request(
        url, headers={"Accept": "application/json", "User-Agent": "fiscalis-health-monitor", **(headers or {})}
    )
    for attempt in range(3):
        try:
            with opener(request, timeout=HTTP_TIMEOUT) as response:
                return json.loads(response.read().decode("utf-8"))
        except urllib.error.HTTPError as error:
            if error.code < 500 or attempt == 2:
                raise NotifyError(f"{what} HTTP {error.code}") from None
        except (urllib.error.URLError, http.client.HTTPException, OSError, ValueError) as error:
            if attempt == 2:
                raise NotifyError(f"{what} {type(error).__name__}") from None
        sleep(2 * (attempt + 1))
    raise AssertionError("unreachable")


def run_audit(settings: Mapping[str, str], opener: Opener, now: float,
              sleep: Callable[[float], None] = time.sleep) -> dict[str, Any]:  # fmt: skip
    """One audit; any problem or error makes it fail."""
    bucket = settings.get("FISCALIS_ARCHIVE_BUCKET", "")
    access, secret = settings.get(AUDIT_KEYS[0], ""), settings.get(AUDIT_KEYS[1], "")
    stats: dict = {}
    if not _BUCKET.fullmatch(bucket) or not access or not secret:
        problems = ["audit credentials (audit-env) missing or incomplete"]
    else:
        try:
            ledger = fetch_json(LEDGER_URL, opener, sleep)
            s3 = S3(bucket, access, secret, opener, sleep=sleep)
            yesterday = datetime.datetime.fromtimestamp(now, datetime.timezone.utc).date() - datetime.timedelta(days=1)
            problems, stats = audit_archive(ledger, s3, bucket, yesterday)
        except Exception as error:  # noqa: BLE001 - an audit that cannot run is a failed audit
            problems = [f"audit error: {error}" if isinstance(error, NotifyError) else f"audit error: {type(error).__name__}"]
    at = datetime.datetime.fromtimestamp(now, datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    detail = "" if not problems else f"{len(problems)} problem(s) at {at}: {problems[0]}"
    return {"ok": not problems, "at": now, "problems": [flatten(p, 200) for p in problems[:10]],
            "problem_count": len(problems), "detail": flatten(detail, 160), **stats}  # fmt: skip


def record_audit(state: dict, result: Mapping[str, Any]) -> dict:
    previous = state.get("audit") if isinstance(state.get("audit"), dict) else {}
    last_success = result["at"] if result["ok"] else previous.get("last_success")
    return {**state, "audit": {**result, "last_success": last_success}}


