@contextlib.contextmanager
def locked(state_dir: pathlib.Path):
    """The poll and the audit share state.json; one at a time."""
    state_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
    with open(state_dir / "lock", "a") as handle:
        fcntl.flock(handle, fcntl.LOCK_EX)
        yield


def read_state(state_file: pathlib.Path) -> Any:
    try:
        return json.loads(state_file.read_text())
    except (OSError, ValueError):
        return None


def save_state(state_file: pathlib.Path, state: Mapping[str, Any]) -> None:
    tmp = state_file.with_suffix(".tmp")
    tmp.write_text(json.dumps(state, indent=2) + "\n")
    tmp.replace(state_file)


def test_alert(send: Callable[[str, str], None], now: float, environ: Mapping[str, str]) -> int:
    """One [TEST] message per channel. It only proves the emergency path when run as
    ``systemctl start fiscalis-health-test.service`` (the monitor's own sandbox and
    systemd credential), which ``credentials`` in the output shows."""
    at = datetime.datetime.fromtimestamp(now, datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    results = {}
    for channel in CHANNELS:
        text = (f"[TEST] Fiscalis health monitor alert path test ({at}). Nothing is wrong; "
                f"this checks that {channel} alerts arrive.")  # fmt: skip
        try:
            send(channel, text)
            results[channel] = "sent"
        except Exception as error:  # noqa: BLE001
            results[channel] = str(error) if isinstance(error, NotifyError) else type(error).__name__
    via = "env file" if environ.get("FISCALIS_HEALTH_ENV") else (
        "systemd credential" if environ.get("CREDENTIALS_DIRECTORY") else "none")
    print(json.dumps({"mode": "test-alert", "credentials": via, "results": results}))
    if via != "systemd credential":
        log("not run by fiscalis-health-test.service: this does not test the production sandbox")
    return 0 if all(r == "sent" for r in results.values()) else 1


def main(
    argv: list[str], *, environ: Mapping[str, str] | None = None, opener: Opener = urllib.request.urlopen,
    runner: Runner = subprocess.run, clock: Callable[[], float] = time.time,
    docker: str | None = None, sleep: Callable[[float], None] = time.sleep,
) -> int:  # fmt: skip
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="poll and print; send, ping and save nothing")
    mode.add_argument("--audit", action="store_true", help="audit the S3 archive, then run as usual")
    mode.add_argument("--test-alert", action="store_true", help="send one TEST message to Slack and WhatsApp")
    parser.add_argument("--digest", action="store_true", help="post the daily sync digest to Slack")
    args = parser.parse_args(argv)
    if args.digest and (args.audit or args.test_alert):
        parser.error("--digest runs alone (or with --dry-run)")
    environ = os.environ if environ is None else environ
    state_dir = pathlib.Path(environ.get("FISCALIS_HEALTH_STATE_DIR", str(STATE_DIR)))
    confirm = int(environ.get("FISCALIS_HEALTH_CONFIRM_RUNS", CONFIRM_RUNS))
    remind = float(environ.get("FISCALIS_HEALTH_REMIND_HOURS", REMIND_HOURS)) * 3600
    settings = load_settings(environ, "FISCALIS_HEALTH_ENV", ("monitor-env", "slack-env"), MONITOR_KEYS)
    docker = docker if docker is not None else shutil.which("docker")
    send = make_sender(settings, environ, opener, runner, docker)
    if args.test_alert:
        return test_alert(send, clock(), environ)
    if args.digest:
        return digest_main(state_dir, settings, opener, clock, sleep, args.dry_run)

    audit = None
    if args.audit:  # the slow network part, outside the lock
        audit_settings = load_settings(environ, "FISCALIS_AUDIT_ENV", ("audit-env",), AUDIT_KEYS)
        audit = run_audit(audit_settings, opener, clock(), sleep)

    state_file = state_dir / "state.json"
    errored, results = False, {}
    try:
        with contextlib.nullcontext() if args.dry_run else locked(state_dir):
            now = clock()
            state = load_state(read_state(state_file), now)
            if audit is not None:
                state = record_audit(state, audit)
            poll = observe(HEALTH_URL, opener)
            observed = audit_checks(state, now)
            new, due = evaluate(state, poll["failing"] + observed, now, confirm, remind)
            new["last"] = poll
            summary = {"mode": "audit" if args.audit else "poll", "dry_run": args.dry_run,
                       "failing": sorted({c["name"] for c in poll["failing"]} | {c["name"] for c in observed}),
                       "counts": new["counts"],
                       "confirmed": new["confirmed"]["set"], "due": due}  # fmt: skip
            if audit is not None:
                summary["audit"] = {k: audit[k] for k in ("ok", "problem_count", "problems")}
            if args.dry_run:
                summary["messages"] = {
                    ch: compose(kind, new["channels"][ch], new["confirmed"], now, slack=ch == "slack")
                    for ch, kind in due.items()
                }
            else:
                results = deliver(new, due, send, now)
                summary["sent"] = results
                save_state(state_file, new)
            print(json.dumps(summary, ensure_ascii=False))
    except Exception as error:  # noqa: BLE001 - reported to the watchdog, then re-raised as exit 1
        errored = True
        log(f"run failed: {type(error).__name__}: {flatten(str(error), 200)}")
    undelivered = any(r != "sent" for r in results.values())
    if not args.dry_run:
        ping(settings, errored or undelivered, opener)
    return 1 if errored or undelivered else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
