#!/usr/bin/python3
"""Fiscalis health monitor: /health/deep and an S3 archive audit, Slack + WhatsApp.

Runs on the Mya VPS. ``fiscalis-health-monitor.timer`` starts a poll every
five minutes; ``fiscalis-health-audit.timer`` starts ``--audit`` daily at
01:30 UTC. See README.md for the runbook.

- **Failing set**: each poll turns the production Convex deployment's
  ``/health/deep`` (frontend/convex/http.ts) into the set of failing check
  names, plus the pseudo-checks ``unreachable`` (no answer, not JSON, a status
  other than 200/503) and ``invalid`` (JSON that is not a health report), plus
  ``archive-audit`` / ``archive-audit-stale`` from the stored audit result. A
  check is *confirmed* on its own once it failed on ``CONFIRM_RUNS`` runs not
  separated by ``CONFIRM_RUNS`` healthy runs, and cleared after that many
  healthy runs in a row; ``unreachable``/``invalid`` polls neither fail nor
  clear the deployment's checks.
- **Routing**: every change of the confirmed set goes to Slack. If the set
  holds a critical check (severity from the body; pseudo-checks and unknown
  names are critical) the message is an EMERGENCY and goes to WhatsApp too,
  as does the recovery from it. While a critical failure stays confirmed both
  channels get a reminder every ``REMIND_HOURS``.
- **Delivery**: each channel remembers what it was last told and only moves
  once its send succeeded, so a failed channel is retried next run and the
  other one is not sent the same message twice.
- **Watchdog**: after each run ``FISCALIS_HC_PING_URL`` (healthchecks.io) is
  pinged, ``/fail`` when the run errored or a due message was not delivered.
- **Audit** (``--audit``): HEADs every ledger day's S3 object (SigV4, stdlib)
  and compares its stored SHA-256 and size with the ledger, and lists the
  bucket to check that every UTC day since 2024-07-09 has an object.
- **Digest** (``--digest``, daily at 07:30 UTC): fetches
  ``/health/sync-digest`` with the shared secret ``FISCALIS_MONITOR_SECRET``
  and posts the last 24 hours of provider sync failures and the stale feeds
  to Slack, once per UTC day. It does not ping the watchdog.
- **Credentials**: systemd credentials ``monitor-env`` (Slack, WhatsApp
  number, ping URL, digest secret) and, for the audit, ``audit-env`` (a read-only IAM key).
  ``FISCALIS_HEALTH_ENV`` / ``FISCALIS_AUDIT_ENV`` name other files. Values
  are never printed.
- **State**: ``/var/lib/fiscalis-health-monitor/state.json`` (a v1 file from
  the first version loads and is migrated).

``--dry-run`` polls and prints what it would send; it needs no credentials,
sends, pings and saves nothing. ``--test-alert`` sends one TEST message to
both channels; ``fiscalis-health-test.service`` (generated by install.sh from the
monitor unit) runs it in the production sandbox. Standard library only.
"""

