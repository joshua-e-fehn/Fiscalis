def read_env(path: pathlib.Path, keys: Iterable[str]) -> dict[str, str]:
    """``KEY=value`` lines of a dotenv file, only `keys` (as camsocs-notify.py's read_env)."""
    wanted, values = set(keys), {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        name, _, value = line.partition("=")
        name = name.strip().removeprefix("export ").strip()
        if name not in wanted:
            continue
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        elif " #" in value:
            value = value.split(" #", 1)[0].rstrip()
        values[name] = value
    return values


def load_settings(environ: Mapping[str, str], override: str, names: Iterable[str], keys: Iterable[str]) -> dict:
    """The first readable of $override or the systemd credentials `names`; {} when none."""
    creds = environ.get("CREDENTIALS_DIRECTORY")
    paths = [environ[override]] if environ.get(override) else []
    paths += [str(pathlib.Path(creds) / n) for n in names] if creds else []
    for path in paths:
        try:
            return read_env(pathlib.Path(path), keys)
        except OSError:
            continue
    return {}


def whatsapp_chat(settings: Mapping[str, str]) -> str | None:
    """The first of ``WHATSAPP_ALLOWED_USERS`` as a WhatsApp chat id, or None."""
    for entry in re.split(r"[,\s]+", settings.get("WHATSAPP_ALLOWED_USERS", "")):
        match = _PHONE.fullmatch(entry.strip())
        if match:
            return f"{match.group(1)}@s.whatsapp.net"
    return None


def slack_post(settings: Mapping[str, str], text: str, opener: Opener) -> None:
    token, channel = settings.get("SLACK_BOT_TOKEN"), settings.get("SLACK_HOME_CHANNEL")
    if not token or not channel:
        raise NotifyError("slack not configured")
    request = urllib.request.Request(
        f"{SLACK_API}/chat.postMessage",
        data=json.dumps(
            {"channel": channel, "text": text, "unfurl_links": False, "unfurl_media": False}
        ).encode("utf-8"),
        headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json; charset=utf-8"},
        method="POST",
    )
    try:
        with opener(request, timeout=HTTP_TIMEOUT) as response:
            answer = json.loads(response.read().decode("utf-8"))
    except (urllib.error.URLError, http.client.HTTPException, OSError, ValueError) as error:
        raise NotifyError(f"slack {type(error).__name__}") from None
    if not isinstance(answer, dict) or not answer.get("ok"):
        code = answer.get("error", "no answer") if isinstance(answer, dict) else "no answer"
        raise NotifyError(f"slack {flatten(str(code), 40)}")


def whatsapp_send(docker: str, container: str, chat_id: str, text: str, runner: Runner) -> None:
    """``POST /send`` on Mya's bridge inside her container, as camsocs-notify.py does.

    Only ``/send``: never ``GET /messages``, which would take Mya's incoming
    messages off her queue.
    """
    body = json.dumps({"chatId": chat_id, "message": text})
    command = [
        docker, "exec", "-i", container,
        "curl", "-sS", "-m", "30", "-X", "POST",
        "-H", "Content-Type: application/json", "--data-binary", "@-", BRIDGE_SEND,
    ]  # fmt: skip
    try:
        done = runner(command, input=body, capture_output=True, text=True,
                      timeout=WHATSAPP_TIMEOUT, check=False)  # fmt: skip
    except subprocess.TimeoutExpired:
        raise NotifyError("whatsapp timeout") from None
    except OSError as error:
        raise NotifyError(f"whatsapp {type(error).__name__}") from None
    if done.returncode != 0:
        raise NotifyError(f"whatsapp exit {done.returncode}")
    try:
        answer = json.loads(done.stdout or "{}")
    except ValueError:
        raise NotifyError("whatsapp bad answer") from None
    if not isinstance(answer, dict) or answer.get("success") is not True:
        raise NotifyError("whatsapp not sent")


def make_sender(settings: Mapping[str, str], environ: Mapping[str, str], opener: Opener,
                runner: Runner, docker: str | None) -> Callable[[str, str], None]:  # fmt: skip
    container = environ.get("FISCALIS_MYA_CONTAINER") or DEFAULT_CONTAINER

    def send(channel: str, text: str) -> None:
        if channel == "slack":
            return slack_post(settings, text, opener)
        chat_id = whatsapp_chat(settings)
        if not docker or not chat_id or not _CONTAINER.fullmatch(container):
            raise NotifyError("whatsapp not configured")
        whatsapp_send(docker, container, chat_id, text, runner)

    return send


def deliver(state: dict, due: Mapping[str, str], send: Callable[[str, str], None], now: float) -> dict:
    """Send what is due; a channel's record moves only once its send succeeded."""
    results = {}
    for channel, kind in due.items():
        told = state["channels"][channel]
        text = compose(kind, told, state["confirmed"], now, slack=channel == "slack")
        try:
            send(channel, text)
        except Exception as error:  # noqa: BLE001 - retried next run; never print a secret
            results[channel] = str(error) if isinstance(error, NotifyError) else type(error).__name__
            state["channels"][channel] = {**told, "error": results[channel]}
            continue
        state["channels"][channel] = told_record(told, state["confirmed"], now)
        results[channel] = "sent"
    return results


def ping(settings: Mapping[str, str], fail: bool, opener: Opener) -> str:
    """The healthchecks.io watchdog; a ping failure never fails the run."""
    url = (settings.get("FISCALIS_HC_PING_URL") or "").rstrip("/")
    if not url:
        log("no FISCALIS_HC_PING_URL: watchdog ping skipped")
        return "skipped"
    if not HC_PING.fullmatch(url):
        log("FISCALIS_HC_PING_URL is not an https://hc-ping.com/ URL: watchdog ping skipped")
        return "skipped"
    request = urllib.request.Request(url + ("/fail" if fail else ""), headers={"User-Agent": "fiscalis-health-monitor"})
    try:
        with opener(request, timeout=PING_TIMEOUT) as response:
            response.read(256)
    except Exception as error:  # noqa: BLE001
        log(f"watchdog ping failed ({type(error).__name__})")
        return "error"
    return "fail" if fail else "ok"


