# --- text ---------------------------------------------------------------------------------


def flatten(value: Any, limit: int) -> str:
    """One line of at most `limit` characters from untrusted text."""
    text = _CONTROL.sub(" ", value if isinstance(value, str) else "")
    text = re.sub(r"\s+", " ", text).strip()
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def slack_escape(text: str) -> str:
    """No link, mention or ``<!channel>`` can form; ``@here`` notifies no one."""
    return (
        text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("@", FULLWIDTH_AT)
    )


def duration(seconds: float | None) -> str:
    if seconds is None:
        return "none yet"
    seconds = max(0, int(seconds))
    if seconds < 3600:
        return f"{seconds // 60}m"
    if seconds < 172800:
        return f"{seconds // 3600}h{(seconds % 3600) // 60:02d}m"
    return f"{seconds // 86400}d{(seconds % 86400) // 3600:02d}h"


def _number(value: Any) -> float | None:
    return float(value) if isinstance(value, (int, float)) and not isinstance(value, bool) else None


# --- observe ------------------------------------------------------------------------------


def failing_check(
    name: str, severity: str = "critical", age: float | None = None,
    threshold: float | None = None, detail: str = "",
) -> dict[str, Any]:  # fmt: skip
    return {"name": name, "severity": severity, "ageSeconds": age, "threshold": threshold,
            "detail": flatten(detail, 160)}  # fmt: skip


def observe(url: str = HEALTH_URL, opener: Opener = urllib.request.urlopen) -> dict[str, Any]:
    """One poll: ``{"ok": bool, "failing": [check, ...], "detail": str}``."""
    request = urllib.request.Request(
        url, headers={"Accept": "application/json", "User-Agent": "fiscalis-health-monitor"}
    )
    try:
        with opener(request, timeout=HTTP_TIMEOUT) as response:
            status, raw = response.status, response.read()
    except urllib.error.HTTPError as error:
        status, raw = error.code, error.read()
    except (urllib.error.URLError, http.client.HTTPException, OSError, ValueError) as error:
        return _pseudo("unreachable", f"no answer ({type(error).__name__})")
    return parse_report(status, raw)


def _pseudo(name: str, detail: str) -> dict[str, Any]:
    return {"ok": False, "failing": [failing_check(name, detail=detail)], "detail": detail}


def parse_report(status: int, raw: bytes) -> dict[str, Any]:
    status = int(status)
    if status not in (200, 503):
        return _pseudo("unreachable", f"HTTP {status}")
    try:
        body = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, ValueError):
        return _pseudo("unreachable", f"HTTP {status}, not JSON")
    if not isinstance(body, dict) or not isinstance(body.get("checks"), list):
        return _pseudo("invalid", f"HTTP {status}, no health report")
    checks = failing_checks(body)
    if not checks and (status != 200 or body.get("ok") is not True):
        checks = [failing_check("invalid", detail=f"HTTP {status} but no failing check named")]
    return {"ok": not checks, "failing": checks, "detail": "healthy" if not checks else f"HTTP {status}"}


def failing_checks(body: Mapping[str, Any]) -> list[dict[str, Any]]:
    """The failing checks of a health report body (``{"checks": [...]}``), shape-checked."""
    failing: dict[str, dict[str, Any]] = {}
    for check in body.get("checks") or []:
        if not isinstance(check, dict):
            failing["invalid"] = failing_check("invalid", detail="a check is not an object")
            continue
        if check.get("ok") is True:
            continue
        name = check.get("name")
        severity = check.get("severity")
        if not isinstance(name, str) or not CHECK_NAME.fullmatch(name) or name in PSEUDO_CHECKS:
            name, severity = "unknown", "critical"
        elif severity not in ("critical", "warning"):
            severity = KNOWN_SEVERITY.get(name, "critical")
        failing[name] = failing_check(
            name, severity, _number(check.get("ageSeconds")), _number(check.get("threshold")),
            check.get("detail") if isinstance(check.get("detail"), str) else "",
        )  # fmt: skip
    return [failing[n] for n in sorted(failing)]


def audit_checks(state: Mapping[str, Any], now: float) -> list[dict[str, Any]]:
    """The stored audit result as failing checks (so reminders and recovery work)."""
    audit = state.get("audit") if isinstance(state.get("audit"), dict) else {}
    out = []
    if audit.get("ok") is False:
        out.append(failing_check("archive-audit", detail=audit.get("detail", "")))
    since = next((t for t in (_number(audit.get("last_success")), _number(state.get("audit_watch_since")))
                  if t is not None), now)  # fmt: skip
    if now - since > AUDIT_STALE_SECONDS:
        out.append(failing_check(
            "archive-audit-stale", age=now - since, threshold=AUDIT_STALE_SECONDS,
            detail="no successful archive audit",
        ))  # fmt: skip
    return out


# --- decide -------------------------------------------------------------------------------


def empty_told() -> dict[str, Any]:
    return {"set": [], "critical": False, "since": None, "reminded_at": None}


def has_critical(confirmed: Mapping[str, Any]) -> bool:
    checks = confirmed.get("checks") or {}
    return any((checks.get(n) or {}).get("severity", "critical") == "critical" for n in confirmed.get("set", []))


def load_state(raw: Any, now: float) -> dict[str, Any]:
    """A v2 state from what state.json held: v2 as is, v1 (ok/fail) migrated, else empty."""
    if not isinstance(raw, dict):
        return {"version": 2}
    if raw.get("version") == 2:
        return raw
    # v1: announced "ok"|"fail" since announced_since; last.failing = the last poll's checks.
    since = _number(raw.get("announced_since"))
    since = now if since is None else since
    names: list[str] = []
    if raw.get("announced") == "fail":
        last = raw.get("last") if isinstance(raw.get("last"), dict) else {}
        found = {c.get("name") for c in last.get("failing") or [] if isinstance(c, dict)}
        names = sorted(n for n in found if isinstance(n, str) and CHECK_NAME.fullmatch(n)) or ["unreachable"]
    checks = {n: failing_check(n, KNOWN_SEVERITY.get(n, "critical")) for n in names}
    confirmed = {"set": names, "since": since, "checks": checks}
    slack = {"set": names, "critical": has_critical(confirmed), "since": since if names else None,
             "reminded_at": since}  # fmt: skip
    return {"version": 2, "confirmed": confirmed, "channels": {"slack": slack, "whatsapp": empty_told()}}


#: Pseudo-checks that mean "this poll says nothing about the deployment's checks".
NO_INFO = {"unreachable", "invalid"}
#: Pseudo-checks from the stored audit result, known on every run.
AUDIT_CHECKS = {"archive-audit", "archive-audit-stale"}


def step(state: Mapping[str, Any], failing: list[dict], now: float, confirm: int = CONFIRM_RUNS) -> dict:
    """Count each check's failures on its own and move ``confirmed`` per check.

    A check joins ``confirmed`` once it failed on `confirm` runs that were not
    separated by `confirm` healthy runs in a row (so a check that fails on every
    other run is confirmed too), and leaves it after `confirm` healthy runs in a
    row. Other checks flapping never hold a check back. A poll that got no
    report (``unreachable``/``invalid``) counts for those pseudo-checks only:
    it neither fails nor clears the deployment's checks.
    """
    new = json.loads(json.dumps(state))
    for stale in ("candidate", "streak", "candidate_since"):  # the whole-set streak of an earlier draft
        new.pop(stale, None)
    confirm = max(1, confirm)
    failed = {c["name"] for c in failing}
    blind = bool(failed & NO_INFO)
    confirmed = new.get("confirmed") or {"set": [], "since": now, "checks": {}}
    counts = new.get("counts") if isinstance(new.get("counts"), dict) else {}
    names = set(counts) | set(confirmed["set"]) | failed
    members = set(confirmed["set"])
    for name in sorted(names):
        count = counts.get(name) if isinstance(counts.get(name), dict) else {}
        fails, oks = int(count.get("fails", 0)), int(count.get("oks", 0))
        if name in failed:
            fails, oks = fails + 1, 0
        elif not blind or name in NO_INFO | AUDIT_CHECKS:
            oks += 1
            if oks >= confirm:
                fails = 0
        if fails >= confirm:
            members.add(name)
        elif oks >= confirm:
            members.discard(name)
        if fails or (name in members):
            counts[name] = {"fails": fails, "oks": oks}
        else:
            counts.pop(name, None)
    new["counts"] = counts
    new["version"], new["checked_at"] = 2, now
    new.setdefault("audit_watch_since", now)
    if sorted(members) != confirmed["set"]:
        confirmed = {"set": sorted(members), "since": now, "checks": confirmed.get("checks") or {}}
    current = {c["name"]: c for c in failing}
    old = confirmed.get("checks") or {}
    confirmed["checks"] = {
        n: current.get(n) or old.get(n) or failing_check(n, KNOWN_SEVERITY.get(n, "critical"))
        for n in confirmed["set"]
    }
    new["confirmed"] = confirmed
    channels = new.setdefault("channels", {})
    for channel in CHANNELS:
        channels.setdefault(channel, empty_told())
    return new


def told_record(told: Mapping[str, Any], confirmed: Mapping[str, Any], now: float) -> dict[str, Any]:
    """What a channel knows after it was told about ``confirmed``."""
    names = list(confirmed["set"])
    since = None
    if names:
        kept = _number(told.get("since")) if told.get("set") else None
        since = kept if kept is not None else confirmed.get("since", now)
    return {"set": names, "critical": has_critical(confirmed), "since": since, "reminded_at": now}


def evaluate(
    state: Mapping[str, Any], failing: list[dict], now: float,
    confirm: int = CONFIRM_RUNS, remind_seconds: float = REMIND_HOURS * 3600,
) -> tuple[dict, dict[str, str]]:  # fmt: skip
    """The next state and the messages due per channel ("change" or "reminder")."""
    new = step(state, failing, now, confirm)
    confirmed, due = new["confirmed"], {}
    critical = has_critical(confirmed)
    for channel in CHANNELS:
        told = new["channels"][channel]
        if sorted(told.get("set") or []) != confirmed["set"]:
            if channel == "slack" or critical or told.get("critical"):
                due[channel] = "change"
            else:  # a warning-only change WhatsApp does not hear about: keep it in step
                new["channels"][channel] = {
                    **told_record(told, confirmed, now), "reminded_at": told.get("reminded_at")
                }
        elif critical and now - (_number(told.get("reminded_at")) or 0) >= remind_seconds:
            due[channel] = "reminder"
    return new, due


def describe(check: Mapping[str, Any], slack: bool) -> str:
    name, severity = check.get("name", "unknown"), check.get("severity", "critical")
    detail = flatten(check.get("detail"), 160)
    threshold = _number(check.get("threshold"))
    if name in ROW_CHECKS:
        facts = detail + (f" (min {int(threshold)} rows)" if threshold is not None else "")
    elif threshold is not None:
        facts = f"age {duration(_number(check.get('ageSeconds')))}, max {duration(threshold)}"
        facts += f" ({detail})" if detail else ""
    else:
        facts = detail or "failing"
    return f"- {name} ({severity}): {slack_escape(facts) if slack else facts}"


def compose(kind: str, told: Mapping[str, Any], confirmed: Mapping[str, Any], now: float, slack: bool) -> str:
    names, before = list(confirmed["set"]), list(told.get("set") or [])
    checks = confirmed.get("checks") or {}
    newly = [n for n in names if n not in before]
    recovered = [n for n in before if n not in names]
    still = [n for n in names if n in before]
    since = _number(told.get("since"))
    critical = has_critical(confirmed)
    if kind == "reminder":
        mark = ":rotating_light:" if slack else "🚨"
        head = f"*EMERGENCY* (reminder): Fiscalis still has a critical failure, for {duration(now - (now if since is None else since))}"
    elif critical:
        mark, head = (":rotating_light:" if slack else "🚨"), "*EMERGENCY*: Fiscalis critical health check failing"
    elif names:
        mark = ":warning:" if slack else "⚠️"
        head = "Fiscalis critical failure recovered, warnings remain" if told.get("critical") else "Fiscalis health warning"
    else:
        mark = ":white_check_mark:" if slack else "✅"
        head = "Fiscalis health recovered" + (f" after {duration(now - since)}" if since is not None else "")
    lines = [f"{mark} {head}"]
    if newly:
        lines += ["Newly failing:"] + [describe(checks.get(n) or {"name": n}, slack) for n in newly]
    if recovered:
        lines.append("Recovered: " + ", ".join(recovered))
    if still:
        lines += ["Still failing:"] + [describe(checks.get(n) or {"name": n}, slack) for n in still]
    lines.append(f"<{HEALTH_URL}|/health/deep>" if slack else HEALTH_URL)
    return "\n".join(lines)


