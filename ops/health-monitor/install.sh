#!/usr/bin/env bash
# Install or update the Fiscalis health monitor and archive audit on the Mya VPS.
#
#   bash install.sh --audit-env /root/fiscalis-audit.env   # install / update, start the timers
#   bash install.sh --digest-env /root/fiscalis-digest.env # also set or rotate the digest secret
#   bash install.sh --dry-run                              # say what would change, change nothing
#   bash install.sh --test-alert                           # also send a TEST alert through the real unit
#   bash install.sh --print-test-unit                      # print the generated test unit (no root needed)
#
# Idempotent; run as root. Copies the script to /usr/local/lib/fiscalis-health-monitor/
# and the units to /etc/systemd/system/ (fiscalis-health-test.service is generated from
# the monitor unit, so a test alert runs in exactly its sandbox), and writes two 0600
# root files:
#
#   /etc/fiscalis-health-monitor/monitor.env  SLACK_BOT_TOKEN, SLACK_HOME_CHANNEL and
#       WHATSAPP_ALLOWED_USERS copied from Mya's env file (her existing bot and
#       bridge: no new app or token), plus FISCALIS_HC_PING_URL (the
#       healthchecks.io check): from $FISCALIS_HC_PING_URL, else kept from the
#       previous monitor.env; and FISCALIS_MONITOR_SECRET (the shared secret of
#       GET /health/sync-digest, also set on Convex) from the 0600 root file named
#       by --digest-env, else kept from the previous monitor.env.
#   /etc/fiscalis-health-monitor/audit.env    FISCALIS_ARCHIVE_AUDIT_ACCESS_KEY_ID,
#       FISCALIS_ARCHIVE_AUDIT_SECRET_ACCESS_KEY and FISCALIS_ARCHIVE_BUCKET, copied
#       from the 0600 file named by --audit-env (or $FISCALIS_AUDIT_KEY_FILE), else
#       kept from the previous audit.env.
#
# No value is ever printed. Re-run after Mya's token changes or to rotate a key.
set -euo pipefail

MYA_ENV="${MYA_ENV:-/docker/hermes-agent-vspa/data/.env}"
LIB_DIR=/usr/local/lib/fiscalis-health-monitor
ETC_DIR=/etc/fiscalis-health-monitor
STATE_DIR=/var/lib/fiscalis-health-monitor
UNIT_DIR=/etc/systemd/system
SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DRY_RUN=0
TEST_ALERT=0
AUDIT_KEY_FILE="${FISCALIS_AUDIT_KEY_FILE:-}"
DIGEST_KEY_FILE=""
while (($#)); do
  case "$1" in
    --dry-run) DRY_RUN=1 ;;
    --test-alert) TEST_ALERT=1 ;;
    --print-test-unit) PRINT_TEST_UNIT=1 ;;
    --audit-env) AUDIT_KEY_FILE="${2:?--audit-env needs a file}"; shift ;;
    --digest-env) DIGEST_KEY_FILE="${2:?--digest-env needs a file}"; shift ;;
    *) printf 'unknown argument: %s\n' "$1" >&2; exit 2 ;;
  esac
  shift
done

say() { printf '[fiscalis-health-monitor] %s\n' "$*"; }
# The monitor unit with ExecStart ... --test-alert and its own runtime directory:
# same user, credential, sandbox and network rules. No [Install]: started by hand only.
test_unit() {
  printf '# GENERATED by install.sh from fiscalis-health-monitor.service: sends one [TEST]\n'
  printf '# alert to Slack and WhatsApp in the monitor'"'"'s own sandbox. Run it with\n'
  printf '# `systemctl start fiscalis-health-test.service`; a non-zero exit means a channel failed.\n'
  sed -e '1,/^\[Unit\]$/{/^#/d;}' \
    -e 's#^Description=.*#Description=Fiscalis health monitor: TEST alert through the production unit#' \
    -e 's#^\(ExecStart=.*/fiscalis-health-monitor\.py\)$#\1 --test-alert#' \
    -e 's#^RuntimeDirectory=fiscalis-health-monitor$#RuntimeDirectory=fiscalis-health-test#' \
    -e 's#/run/fiscalis-health-monitor#/run/fiscalis-health-test#g' \
    "$SRC/fiscalis-health-monitor.service"
}
if ((${PRINT_TEST_UNIT:-0})); then test_unit; exit 0; fi
run() { if ((DRY_RUN)); then say "would run: $*"; else "$@"; fi; }
lines() { grep -E "^[[:space:]]*(export[[:space:]]+)?($1)[[:space:]]*=" "$2" || true; }
has() { grep -Eq "^[[:space:]]*(export[[:space:]]+)?$1[[:space:]]*=[[:space:]]*[^[:space:]]" "$2"; }

[[ $EUID -eq 0 ]] || { say "run as root"; exit 1; }
[[ -r "$MYA_ENV" ]] || { say "$MYA_ENV is not readable: no Slack or WhatsApp settings"; exit 1; }
for key in SLACK_BOT_TOKEN SLACK_HOME_CHANNEL WHATSAPP_ALLOWED_USERS; do
  has "$key" "$MYA_ENV" || { say "$MYA_ENV lacks $key; not installing"; exit 1; }
done
command -v docker >/dev/null || { say "no docker CLI: WhatsApp alerts cannot be sent; not installing"; exit 1; }

# --- the healthchecks.io ping URL ----------------------------------------------
ping_line=""
if [[ -n "${FISCALIS_HC_PING_URL:-}" ]]; then
  [[ "$FISCALIS_HC_PING_URL" =~ ^https://hc-ping\.com/[A-Za-z0-9_/-]+$ ]] ||
    { say "FISCALIS_HC_PING_URL is not an https://hc-ping.com/ URL"; exit 1; }
  ping_line="FISCALIS_HC_PING_URL=$FISCALIS_HC_PING_URL"
elif [[ -r "$ETC_DIR/monitor.env" ]]; then
  ping_line="$(lines FISCALIS_HC_PING_URL "$ETC_DIR/monitor.env" | tail -n 1)"
fi
[[ -n "$ping_line" ]] || say "WARNING: no FISCALIS_HC_PING_URL: nothing will notice if the monitor stops"

# --- the digest secret ---------------------------------------------------------
root_only() { # root_only <file>: a regular 0600 root file, or exit
  [[ -f "$1" && ! -L "$1" ]] || { say "$1 is not a regular file"; exit 1; }
  [[ "$(stat -c %a "$1")" == 600 && "$(stat -c %u "$1")" == 0 ]] ||
    { say "$1 must be mode 0600 and owned by root"; exit 1; }
}
secret_line=""
if [[ -n "$DIGEST_KEY_FILE" ]]; then
  root_only "$DIGEST_KEY_FILE"
  secret_line="$(lines FISCALIS_MONITOR_SECRET "$DIGEST_KEY_FILE" | tail -n 1)"
  [[ "$secret_line" =~ =[[:space:]]*[A-Za-z0-9_-]{32,}[[:space:]]*$ ]] ||
    { say "$DIGEST_KEY_FILE lacks FISCALIS_MONITOR_SECRET (32+ characters of [A-Za-z0-9_-])"; exit 1; }
elif [[ -r "$ETC_DIR/monitor.env" ]]; then
  secret_line="$(lines FISCALIS_MONITOR_SECRET "$ETC_DIR/monitor.env" | tail -n 1)"
fi
[[ -n "$secret_line" ]] || say "WARNING: no FISCALIS_MONITOR_SECRET: the daily digest will only report that (pass --digest-env)"

# --- the audit key -------------------------------------------------------------
AUDIT_KEYS="FISCALIS_ARCHIVE_AUDIT_ACCESS_KEY_ID|FISCALIS_ARCHIVE_AUDIT_SECRET_ACCESS_KEY|FISCALIS_ARCHIVE_BUCKET"
audit_source=""
if [[ -n "$AUDIT_KEY_FILE" ]]; then
  root_only "$AUDIT_KEY_FILE"
  audit_source="$AUDIT_KEY_FILE"
elif [[ -r "$ETC_DIR/audit.env" ]]; then
  audit_source="$ETC_DIR/audit.env"
else
  say "no audit key: pass --audit-env FILE (see README, 'Archive audit'); not installing"
  exit 1
fi
for key in FISCALIS_ARCHIVE_AUDIT_ACCESS_KEY_ID FISCALIS_ARCHIVE_AUDIT_SECRET_ACCESS_KEY FISCALIS_ARCHIVE_BUCKET; do
  has "$key" "$audit_source" || { say "$audit_source lacks $key; not installing"; exit 1; }
done

write_secret() { # write_secret <target> <description>; content on stdin
  if ((DRY_RUN)); then cat >/dev/null; say "would write $1 (0600 root: $2)"; return; fi
  local tmp
  tmp="$(mktemp "$ETC_DIR/.env.XXXXXX")"
  chmod 0600 "$tmp"
  cat >"$tmp"
  mv -f "$tmp" "$1"
  say "wrote $1 (0600 root: $2)"
}

run install -d -m 0755 -o root -g root "$LIB_DIR"
run install -m 0755 -o root -g root "$SRC/fiscalis-health-monitor.py" "$LIB_DIR/"
for unit in fiscalis-health-monitor.service fiscalis-health-monitor.timer \
  fiscalis-health-audit.service fiscalis-health-audit.timer \
  fiscalis-health-digest.service fiscalis-health-digest.timer; do
  run install -m 0644 -o root -g root "$SRC/$unit" "$UNIT_DIR/"
done
if ((DRY_RUN)); then
  say "would write $UNIT_DIR/fiscalis-health-test.service (generated from the monitor unit)"
else
  test_unit >"$UNIT_DIR/fiscalis-health-test.service"
  chmod 0644 "$UNIT_DIR/fiscalis-health-test.service"
fi
run install -d -m 0750 -o root -g root "$ETC_DIR"
{
  lines 'SLACK_BOT_TOKEN|SLACK_HOME_CHANNEL|WHATSAPP_ALLOWED_USERS' "$MYA_ENV"
  [[ -z "$ping_line" ]] || printf '%s\n' "$ping_line"
  [[ -z "$secret_line" ]] || printf '%s\n' "$secret_line"
} | write_secret "$ETC_DIR/monitor.env" "Slack, the WhatsApp number, the ping URL, the digest secret"
if [[ "$audit_source" != "$ETC_DIR/audit.env" ]]; then
  lines "$AUDIT_KEYS" "$audit_source" | write_secret "$ETC_DIR/audit.env" "the read-only archive audit key"
fi

# The first version ran with DynamicUser=yes, so its state lives in
# /var/lib/private behind a symlink. The units now run as root: move it back.
if [[ -L "$STATE_DIR" && -d "/var/lib/private/fiscalis-health-monitor" ]]; then
  run systemctl stop fiscalis-health-monitor.timer
  run rm "$STATE_DIR"
  run mv /var/lib/private/fiscalis-health-monitor "$STATE_DIR"
  run chown -R root:root "$STATE_DIR"
fi

run systemctl daemon-reload
run systemctl enable --now fiscalis-health-monitor.timer fiscalis-health-audit.timer fiscalis-health-digest.timer
run rm -f "$ETC_DIR/slack.env" # the first version's credential, replaced by monitor.env
say "poll now (prints the decision, sends nothing):"
run /usr/bin/python3 -I "$LIB_DIR/fiscalis-health-monitor.py" --dry-run
if ((TEST_ALERT)) && ! ((DRY_RUN)); then
  say "sending a [TEST] alert through fiscalis-health-test.service (the monitor's sandbox):"
  test_ok=1
  systemctl start fiscalis-health-test.service || test_ok=0
  journalctl -u fiscalis-health-test.service -n 5 --no-pager -o cat || true
  ((test_ok)) || { say "TEST ALERT FAILED: a real emergency would not get through"; exit 1; }
  say "test alert sent to Slack and WhatsApp: check that both arrived"
else
  say "next: systemctl start fiscalis-health-audit.service, then systemctl start fiscalis-health-test.service (README)"
fi
